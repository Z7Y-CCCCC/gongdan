function processTableHeaders() {
  const ths = document.querySelectorAll('th');
  ths.forEach(th => {
    // 过滤车间看板中的 th
    if (th.closest('.dashboard-fullscreen')) {
      return;
    }
    // 过滤复选框或已被包装的 th
    if (th.querySelector('.th-container') || th.querySelector('input[type="checkbox"]') || th.classList.contains('check-cell')) {
      return;
    }
    const text = th.innerText.trim();
    if (!text) return;
    
    // 从映射中匹配对应的 SVG
    let iconSvg = iconMap[text];
    if (!iconSvg) {
      // 模糊匹配关键字
      const matchedKey = Object.keys(iconMap).find(k => text.includes(k));
      if (matchedKey) {
        iconSvg = iconMap[matchedKey];
      } else {
        // 默认兜底图标 (小书签/文档类图标)
        iconSvg = `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>`;
      }
    }
    
    // 保留 th 原有内容（比如可能会有 * 标志或排序图标）
    const innerHtml = th.innerHTML;
    
    // 包装内部元素
    th.innerHTML = `
      <div class="th-container">
        <span class="th-icon-wrapper">${iconSvg}</span>
        <span class="th-text">${innerHtml}</span>
      </div>
    `;
  });
}

// 采用 MutationObserver 高效感知 DOM 变化，自动为所有新表格表头注入图标
const observer = new MutationObserver(() => {
  processTableHeaders();
});

// 在 DOM 加载就绪后启动监听
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', () => {
    processTableHeaders();
    observer.observe(document.body, { childList: true, subtree: true });
  });
} else {
  processTableHeaders();
  observer.observe(document.body, { childList: true, subtree: true });
}

// 额外每 200ms 执行一次兜底处理，确保任何极其复杂的动态异步场景 100% 被覆盖
setInterval(processTableHeaders, 200);

createApp(App).mount('#app')

