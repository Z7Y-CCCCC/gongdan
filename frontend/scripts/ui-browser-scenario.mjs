// Manual QA of production dist. Start ui-browser-fixture.mjs, open its loopback
// URL in a fresh playwright-cli session, then run-code --filename this file
// from the repository root. Screenshots belong in output/playwright/management-ui.
// This scenario must never run against a real backend or real business data.
async (page) => {
  const origin = new URL(page.url()).origin
  if (new URL(origin).hostname !== '127.0.0.2') throw new Error('Use the isolated UI fixture')
  const probe = await page.request.get(`${origin}/api/fixture-state`)
  const fixture = await probe.json()
  if (!probe.ok() || fixture.fixture !== 'management-ui') throw new Error('Unsupported fixture')
  const errors = []
  const onError = error => errors.push(error.message)
  page.on('pageerror', onError)
  const checks = []
  const check = (condition, label) => {
    if (!condition) throw new Error(label)
    checks.push(label)
  }
  const capture = async name => {
    await page.locator('.workspace-loading-overlay').waitFor({ state: 'hidden' })
    return page.screenshot({ path: `output/playwright/management-ui/${name}.png`, animations: 'disabled' })
  }
  try {
    await page.setViewportSize({ width: 1280, height: 800 })
    if (await page.getByRole('textbox', { name: '工厂代码', exact: true }).isVisible()) {
      const card = await page.locator('.login-box').boundingBox()
      check(card && Math.abs(card.x + card.width / 2 - 640) < 2, 'Login card is centered')
      await capture('login')
      await page.setViewportSize({ width: 390, height: 844 })
      check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'Narrow login has no horizontal overflow')
      await capture('login-narrow')
      await page.setViewportSize({ width: 1280, height: 800 })
      await page.getByRole('textbox', { name: '工厂代码', exact: true }).fill('UIFIXTURE')
      await page.getByRole('textbox', { name: '用户名', exact: true }).fill('admin')
      await page.getByRole('textbox', { name: '密码', exact: true }).fill('fixture-27')
      await page.getByRole('button', { name: '登录', exact: true }).click()
    }
    const home = page.getByRole('button', { name: '主页', exact: true })
    await home.focus()
    await page.keyboard.press('Enter')
    await page.locator('[data-home-view="task-first"]').waitFor()
    check(await page.locator('.home-topbar-right').count() === 0, 'Active home omits duplicate user identity')
    check(await page.locator('a.nav-item:not([role="button"]), a.sub-item:not([role="button"])').count() === 0, 'Sidebar commands are keyboard-addressable')
    await capture('home')

    await page.locator('.work-order-progress__view-link').first().click()
    const detail = page.getByRole('dialog', { name: '工单详情', exact: true })
    await detail.getByRole('heading', { name: 'GD-20261124-001', exact: true }).waitFor()
    const afterView = await (await page.request.get(`${origin}/api/fixture-state`)).json()
    check(afterView.requests.some(request => request.method === 'GET' && request.route === '/work-orders/1'), 'Home opens the actual target through a single-order GET')
    check(afterView.requests.every(request => request.method === 'GET' || request.route === '/auth/login'), 'Viewing a work order does not write business data')
    await capture('home-work-order-detail')
    await detail.getByRole('button', { name: '关闭工单详情', exact: true }).click()
    await detail.waitFor({ state: 'hidden' })
    check(await page.locator('.work-order-progress__view-link').first().evaluate(el => document.activeElement === el), 'Closing the drawer returns focus to the same order on the home page')

    const orders = page.getByRole('button', { name: '工单', exact: true })
    if (!await orders.isVisible()) await page.getByRole('button', { name: '生产管理', exact: true }).click()
    await orders.focus()
    await page.keyboard.press('Space')
    await page.getByRole('button', { name: '创建工单', exact: true }).waitFor()
    await page.getByText('GD-20261124-003', { exact: true }).waitFor()
    check(await page.locator('thead .ui-icon').count() === 0, 'Table labels have no global decorative injection')
    const iconIssues = await page.locator('button.ui-icon-button').evaluateAll(buttons => buttons.filter(button => {
      const box = button.getBoundingClientRect()
      return box.height > 0 && (!button.getAttribute('aria-label') || box.width < 35.9 || box.height < 35.9)
    }).map(button => button.getAttribute('aria-label')))
    check(iconIssues.length === 0, `Named full-sized icon actions: ${iconIssues.join(',')}`)
    await capture('work-orders')
    const deleteTrigger = page.getByRole('button', { name: '删除工单', exact: true }).first()
    await deleteTrigger.click()
    const confirm = page.getByRole('dialog', { name: '删除确认', exact: true })
    await confirm.waitFor()
    check(await confirm.getByRole('button', { name: '确认删除', exact: true }).innerText() === '删除', 'Destructive action names its outcome')
    await capture('delete-confirm')
    await page.keyboard.press('Escape')
    await confirm.waitFor({ state: 'hidden' })
    check(await deleteTrigger.evaluate(element => element === document.activeElement), 'Delete dialog returns focus to its opener')

    await page.getByRole('button', { name: '基础数据', exact: true }).click()
    await page.getByRole('button', { name: '单位', exact: true }).click()
    const columnsTrigger = page.getByRole('button', { name: '字段配置', exact: true })
    await columnsTrigger.click()
    const dialog = page.getByRole('dialog', { name: '列设置', exact: true })
    await dialog.waitFor()
    const close = dialog.getByRole('button', { name: '关闭', exact: true })
    const apply = dialog.getByRole('button', { name: '应用列设置', exact: true })
    check(await dialog.locator('.column-settings-head .column-check-cell span').evaluate(element => element.getClientRects().length === 1), 'Select-all label stays on one line')
    await apply.focus()
    await page.keyboard.press('Tab')
    check(await close.evaluate(element => element === document.activeElement), 'Tab loops within column settings')
    await page.keyboard.press('Shift+Tab')
    check(await apply.evaluate(element => element === document.activeElement), 'Shift+Tab loops within column settings')
    await dialog.getByRole('checkbox', { name: '全部', exact: true }).uncheck()
    check(await apply.isDisabled(), 'Cannot hide every table column')
    await dialog.getByText('至少显示一列', { exact: true }).waitFor()
    await page.keyboard.press('Escape')
    await dialog.waitFor({ state: 'hidden' })
    check(await columnsTrigger.evaluate(element => element === document.activeElement), 'Column settings returns focus')
    await page.getByRole('button', { name: '切换深色主题', exact: true }).click()
    await columnsTrigger.click()
    await dialog.waitFor()
    await capture('column-settings-dark')
    await page.setViewportSize({ width: 640, height: 800 })
    const bounds = await dialog.boundingBox()
    check(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 641, 'Narrow dialog fits its viewport')
    await capture('column-settings-narrow')
    await page.keyboard.press('Escape')
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.getByRole('button', { name: '切换浅色主题', exact: true }).click()

    await page.getByRole('button', { name: '通知', exact: true }).click()
    await page.getByRole('button', { name: '查看全部通知', exact: true }).click()
    await page.locator('.notification-dropdown').waitFor({ state: 'hidden' })
    const notificationPage = page.locator('.notification-center-page')
    const refresh = notificationPage.getByRole('button', { name: '刷新通知', exact: true })
    await refresh.waitFor()
    await page.getByRole('button', { name: /报工待审批/ }).waitFor()
    await capture('notifications')
    await page.route('**/api/notifications?*', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ message: '测试网络故障' }) }))
    await refresh.click()
    await page.getByText('测试网络故障', { exact: false }).waitFor()
    check(await notificationPage.locator('.notification-center-summary').count() === 0, 'Failed requests do not claim zero records')
    await capture('notifications-error')
    await page.unroute('**/api/notifications?*')
    await page.getByRole('button', { name: '重试', exact: true }).click()
    await page.getByRole('button', { name: /报工待审批/ }).waitFor()
    checks.push('Notification failure has an actionable retry')
    await page.emulateMedia({ reducedMotion: 'reduce' })
    const motion = await refresh.evaluate(element => ({ transition: getComputedStyle(element).transitionDuration, animation: getComputedStyle(element).animationName }))
    check(motion.transition.split(',').every(value => parseFloat(value) === 0) && motion.animation === 'none', 'Reduced-motion preference disables effects')
    await page.emulateMedia({ reducedMotion: 'no-preference' })
    check(errors.length === 0, `No application script errors: ${errors.join('; ')}`)
    return { passed: checks.length, checks, intentionalHttpFailures: 1, screenshots: 'output/playwright/management-ui' }
  } finally {
    await page.unroute('**/api/notifications?*')
    page.removeListener('pageerror', onError)
  }
}
